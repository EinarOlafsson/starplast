def grade(frac: float, filled: bool, unit: str) -> str:
    """A for genome-wide and measured, B for partial, C for thin or indirect, - for empty."""
    if not filled:
        return "-"
    if unit == "pair":
        return "A" if frac >= 0.25 else ("B" if frac >= 0.05 else "C")
    return "A" if frac >= 0.8 else ("B" if frac >= 0.2 else "C")


def _cited(row) -> str:
    """The candidates for one slot, each as its title, year and accession -- not a bare PMID.

    A proposal that names an identifier and nothing else asks the reader to go and look up what is
    being proposed, which is most of the work of reading a list like this.
    """
    out = []
    for token in (row["candidates"] or "").split(";"):
        token = token.strip()
        if not token:
            continue
        if not token.startswith("PMID "):
            out.append(token)
            continue
        parts = token.split()
        pmid = parts[1]
        rest = " ".join(parts[2:])
        acc = rest.split("(")[0].strip()
        year, journal, title = REFERENCES.get(pmid, ("", "", ""))
        link = f"[{pmid}](https://pubmed.ncbi.nlm.nih.gov/{pmid}/)"
        bits = [f"**{title}**" if title else "", f"({journal} {year})".strip() if journal else year,
                link, f"`{acc}`" if acc else ""]
        out.append(" ".join(b for b in bits if b))
    return "<br>".join(out)


def _write_markdown(rows, path=OUT_MD) -> None:
    """The same table, rendered. One file to read, one file to compute with."""
    by_axis = {}
    for r in rows:
        by_axis.setdefault(r["axis"], []).append(r)
    lines = [PROSE]
    counts = {g: sum(1 for r in rows if r["grade"] == g) for g in ("A", "B", "C", "-")}
    lines.append(f"**{len(rows)} slots: {counts['A']} covered well, {counts['B']} partly, "
                 f"{counts['C']} thinly, {counts['-']} empty.**\n")
    for axis, group in by_axis.items():
        lines.append(f"### {axis}\n")
        lines.append("| slot | context | grade | genes | coverage | filled by | policy | "
                     "candidates to fill or improve it |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for r in group:
            lines.append(f"| {r['slot']} | {r['context']} | **{r['grade']}** | "
                         f"{r['genes'] or ''} | {r['coverage']} | `{r['filled_by']}` | "
                         f"{r['policy']} | {_cited(r) or '—'} |")
        lines.append("")

    # One dataset, several slots -- the many-to-many, read off the table itself.
    shared = {}
    for r in rows:
        for token in (r["candidates"] or "").split(";"):
            token = token.strip()
            if token.startswith("PMID "):
                pmid = token.split()[1]
                shared.setdefault(pmid, []).append(r["slot"])
    multi = {p: s for p, s in shared.items() if len(s) > 1}
    for r in rows:
        for col in r["filled_by"].split(", "):
            if col and not col.startswith("edge:"):
                shared.setdefault(col, []).append(r["slot"])
    multi_cols = {c: s for c, s in shared.items()
                  if len(s) > 1 and not c.isdigit()}
    if multi or multi_cols:
        lines.append("### One dataset, several slots\n")
        lines.append("Read off the table above: this is the many-to-many the mechanism has to "
                     "carry, not a special case.\n")
        lines.append("| dataset or column family | slots it fills |")
        lines.append("|---|---|")
        for key, slots in list(multi.items()) + list(multi_cols.items()):
            name = (f"[PMID {key}](https://pubmed.ncbi.nlm.nih.gov/{key}/)" if key.isdigit()
                    else f"`{key}`")
            lines.append(f"| {name} | {'; '.join(sorted(set(slots)))} |")
        lines.append("")
    open(path, "w", encoding="utf8").write("\n".join(lines))


def _rows(definitions, nodes, graph, metabolites=None, bridges=None, pf_nodes=None) -> list:
    """One row per slot. `metabolites` is the table whose rows are compounds; slots declaring
    `unit="metabolite"` are graded against it and against its own denominator."""
    metabolites = pd.DataFrame() if metabolites is None else metabolites
    bridges = pd.DataFrame() if bridges is None else bridges
    pf_nodes = pd.DataFrame() if pf_nodes is None else pf_nodes
    """Definitions with measured cache coverage attached."""
    import numpy as np
    n_genes, rows = len(nodes), []
    for definition in definitions:
        slot, axis = definition["name"], definition["axis"]
        context, unit = definition["context"], definition["unit"]
        fills, policy, cands = definition["patterns"], definition["policy"], definition["candidates"]
        edges = [value[len("edge:"):] for value in fills if value.startswith("edge:")]
        columns = [value for value in fills
                   if not value.startswith("edge:") and not value.startswith("bridge:")]
        crossing = [v.split(":", 1)[1] for v in fills if v.startswith("bridge:")]
        if crossing:
            # A bridge is graded on the pairs it carries and the parasite genes it reaches, because
            # its other end is not in this table at all.
            rows_for = bridges[bridges.get("bridge", "").isin(crossing)] if len(bridges) else bridges
            pairs = int(len(rows_for))
            covered = int(rows_for["gene_id"].nunique()) if pairs else 0
            detail = f"{pairs:,} pairs, {covered} parasite gene(s)"
        elif edges:
            key = f"{edges[0]}__a"
            pairs = int(len(graph[key])) if key in graph.files else 0
            covered = int(len(set(np.concatenate([graph[f"{edges[0]}__a"],
                                                   graph[f"{edges[0]}__b"]])))) if key in graph.files else 0
            detail = f"{pairs:,} pairs"
        elif unit == "metabolite" and definition["organism"] == "Tg":
            # Resolved against the metabolite table, whose rows are compounds. Graded on its own
            # denominator: 400 of 1,102 metabolites is most of what anyone has measured, and scoring
            # it out of 8,140 genes would report a full table as 5% covered.
            covered, cols = coverage(metabolites, columns)
            detail = f"{len(cols)} columns of {len(metabolites):,} metabolites" if cols else ""
        elif definition["organism"] == "Tg":
            covered, cols = coverage(nodes, columns)
            detail = f"{len(cols)} columns" if cols else ""
        elif definition["organism"] == "Pf" and len(pf_nodes):
            # Graded against the Plasmodium table and ITS gene count. Scoring 5,720 falciparum
            # genes out of 8,140 gondii ones would report a complete column as 70% covered.
            covered, cols = coverage(pf_nodes, columns)
            detail = f"{len(cols)} columns" if cols else ""
        else:
            covered, cols, detail = 0, [], ""
        if unit == "metabolite":
            denominator = len(metabolites)
        elif definition["organism"] == "Pf":
            denominator = len(pf_nodes)
        else:
            denominator = n_genes
        frac = covered / denominator if denominator else 0.0
        key = f"{definition['organism']}_{slot}"
        verdict, searched, wanted = BLOCKED.get(key, ("", "", ""))
        rows.append({
            "organism": definition["organism"],
            "slot": key, "axis": axis, "context": context,
            "unit": unit, "grade": grade(frac, bool(covered), unit), "genes": covered,
            "coverage": f"{frac:.1%}" if covered else "",
            "filled_by": ", ".join([f"bridge:{c}" for c in crossing] or edges or columns), "detail": detail, "policy": policy,
            "candidates": "; ".join(f"PMID {p} {a}".strip() + (f" ({note})" if note else "")
                                    for p, a, note in cands),
            "candidate_titles": " | ".join(
                f"{p}: {REFERENCES.get(p, ('', '', note))[2]}" if p else note
                for p, a, note in cands),
            # Only meaningful for an empty slot, and left blank rather than invented for a filled one.
            "blocked_by": verdict if not covered else "",
            "searched": searched if not covered else "",
            "would_fill_it": wanted if not covered else "",
        })
    return rows


def _write_csv(rows, path) -> None:
    """Write one reproducible LF-delimited slot table."""
    with open(path, "w", newline="", encoding="utf8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _nested_tree(definitions: list, facet: str, organism: str) -> dict:
    """Build one hierarchy facet without importing the generated runtime catalogue."""
    out = {}
    for row in definitions:
        if row["organism"] != organism:
            continue
        key = f"{organism}_{_slug(row['name'])}"
        branch = out
        for part in tuple(row[f"{facet}_path"]) + (key,):
            branch = branch.setdefault(part, {})
    return out


def _tree_lines(tree: dict, depth: int = 0) -> list:
    lines = []
    for key, child in tree.items():
        lines.append(f"{'  ' * depth}- {key}")
        lines.extend(_tree_lines(child, depth + 1))
    return lines


def _write_hierarchy(definitions: list) -> None:
    trees = {organism: {facet: _nested_tree(definitions, facet, organism)
                        for facet in ("evidence", "biology", "context")}
             for organism in ("Tg", "Pf")}
    with open(OUT_HIERARCHY_JSON, "w", encoding="utf8") as fh:
        json.dump(trees, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    lines = ["# Slot relationship hierarchy", "",
             "Slots are the leaves of three independent trees. A single tree would create false "
             "relationships: for example, membrane topology is sequence evidence about localization, "
             "and a stage RNA-seq experiment also has an in-vivo or in-vitro context.", "",
             "- **Evidence** controls assay/data-class holdouts: what kind of observation was made.",
             "- **Biology** groups the subject being inferred or interpreted.",
             "- **Context** groups the experimental system and stage.",
             "- **Provenance and derivation are a graph, not a tree.** Dataset registry entries and "
             "`derived_from` edges provide the closure used by leakage exclusion.", ""]
    for facet in ("evidence", "biology", "context"):
        lines.extend((f"## Toxoplasma — {facet}", "", *_tree_lines(trees["Tg"][facet]), ""))
    open(OUT_HIERARCHY_MD, "w", encoding="utf8").write("\n".join(lines))


