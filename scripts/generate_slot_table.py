PROSE = """# Slots: one place per question, and a choice about what fills it

**Generated by `scripts/generate_slot_table.py` -- edit the slot list there, not this file.**
Coverage is counted from the shipped cache on every run, so a number here is never a memory.

## What a slot is

    slot        the question, in the map's own terms  ("how much is this gene translated")
    context     the condition it was asked under -- part of the question, not a detail
    candidates  the datasets that answer it, each with its coverage and its assay
    policy      what to do when more than one is chosen
    provenance  which dataset supplied which gene, kept per gene, not per slot

Two things follow from treating a slot as a question rather than as a dataset:

* **The condition is part of the question.** Transcription in a naive macrophage and transcription
  in an IFN-gamma-stimulated one are two slots. A map built on one is not a map built on the other,
  and averaging them answers neither.
* **A dataset fills as many slots as it measured, and a slot takes as many datasets as answer it.**
  One study profiling both macrophage states fills two slots; the seven CRISPR screens fill seven
  fitness slots between them; `rna108740_*` fills the tachyzoite and the bradyzoite slot. The
  mapping is many-to-many in both directions, which is why this is a table and not a tree.

## Why slots at all

`BLOCKS` already normalises each block to equal variance before weighting, so column count does not
decide influence today. What is missing is that a block is defined by a column-name regex -- a fact
about how a file was written -- and that nothing records that the three transcriptomes in the cache
are alternatives rather than three answers.

## The policies

| policy | what it does | when it is right |
|---|---|---|
| `one` | use the chosen dataset, ignore the rest | assays that are not comparable |
| `average` | rank-normalise each, then mean | replicates of the same measurement |
| `fill` | best-covered first, gaps from the next, source recorded per gene | the orthoLOPIT pattern |
| `separate` | keep both, sharing the slot's variance | when the disagreement is the signal |

`average` rank-normalises first because this project has already paid for that lesson: the seven
CRISPR screens differ 64-fold in spread, so a raw mean is an average of one screen. `fill` writes a
`<slot>_source` column exactly as `compartment_source` does, so an inference never reads as a
measurement.

**The circularity guard gets better, not worse.** `excluded_for` reasons about columns, datasets and
quantities today; with slots it can exclude by slot, which is what shared provenance and shared
quantity were approximating on 2026-08-13.

## Grades

**A** genome-wide and measured (>=80% of genes, or >=25% of genes for a pair-wise slot).
**B** partial (>=20%). **C** thin or indirect (<20%). **-** nothing fills it.

"""

