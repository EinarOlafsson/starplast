"""The slot table: one row per question the map can ask, graded against the shipped cache.

A slot is a QUESTION -- "how much is this gene transcribed in an IFN-gamma-stimulated macrophage" --
not a dataset and not a column family. Two consequences, and both are why this file exists rather
than a paragraph of prose:

* **The condition is part of the question.** Transcription in a naive macrophage and transcription
  in an IFN-gamma-stimulated one are two slots, because a map built on one is not a map built on the
  other, and averaging them answers neither.
* **A dataset fills as many slots as it measured.** One study that profiled both macrophage states
  fills both slots; the seven CRISPR screens fill seven fitness slots between them. The mapping is
  many-to-many in both directions, so it is written as a table rather than as a tree.

Coverage is measured, never remembered: every filled slot names the columns or the edge type that
fill it, and this script counts how many genes actually carry a value. Run it after any build.
"""
