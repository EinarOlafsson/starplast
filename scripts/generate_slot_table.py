def _context_path(context: str) -> tuple:
    """Coarse experimental-system tree; exact context remains on the slot itself."""
    low = context.lower()
    if any(word in low for word in ("mouse", "brain", "feline", "enteric", "in vivo")):
        system = "in vivo"
    elif any(word in low for word in ("macrophage", "hff", "host", "neuron", "erythrocyte",
                                      "hepatocyte", "sera")):
        system = "host-cell or host-derived"
    elif any(word in low for word in ("sequence", "orthomcl", "interpro", "alphafold",
                                      "foldseek", "protein")):
        system = "reference or computational"
    else:
        system = "in vitro or assay-defined"
    stage = next((stage for stage in ("tachyzoite", "bradyzoite", "oocyst", "sporozoite",
                                      "merozoite", "sexual", "gametocyte", "liver stage")
                  if stage in low), "stage-unspecified")
    return (system, stage)


